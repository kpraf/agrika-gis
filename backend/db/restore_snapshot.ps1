# ============================================================
#  AgriKA-GIS - restore the database snapshot
#  Run in PowerShell from the project root:
#    powershell -ExecutionPolicy Bypass -File .\backend\db\restore_snapshot.ps1
#
#  It will:
#    1. Find your PostgreSQL 18 install
#    2. Ask for your 'postgres' password (set at install time)
#    3. Drop and recreate the 'agrika_gis' database
#    4. Restore the newest snapshot in backend/db/snapshot/
#       (all data the app uses, including the faithful-model predictions)
#    5. Write backend/.env if you don't have one yet
#
#  The snapshot has NO user accounts. After restoring, create your login:
#    cd backend
#    .\venv\Scripts\python.exe scripts\create_user.py
#
#  Needs PostgreSQL 18 with PostGIS (same as the main setup guide).
#  This REPLACES your local agrika_gis database, including old local logins.
# ============================================================

# Keep "Continue": psql/pg_restore write NOTICEs to stderr, which PowerShell 5.1
# would treat as fatal under "Stop". We check $LASTEXITCODE instead.
$ErrorActionPreference = "Continue"
$scriptDir  = $PSScriptRoot
$backendDir = Split-Path $scriptDir -Parent

Write-Host ""
Write-Host "=== AgriKA-GIS snapshot restore ===" -ForegroundColor Green
Write-Host ""

# --- 1. Locate psql + pg_restore ---
$binDir = Get-ChildItem "C:\Program Files\PostgreSQL\*\bin\pg_restore.exe" -ErrorAction SilentlyContinue |
          Sort-Object FullName -Descending | Select-Object -First 1 | ForEach-Object { $_.DirectoryName }
if (-not $binDir) {
    Write-Host "Could not find pg_restore.exe under C:\Program Files\PostgreSQL." -ForegroundColor Red
    Write-Host "Is PostgreSQL 18 installed?" -ForegroundColor Red
    exit 1
}
$psql      = Join-Path $binDir "psql.exe"
$pgRestore = Join-Path $binDir "pg_restore.exe"
Write-Host "Found PostgreSQL:" (Split-Path $binDir -Parent)

$dump = Get-ChildItem (Join-Path $scriptDir "snapshot\*.dump") -ErrorAction SilentlyContinue |
        Sort-Object Name -Descending | Select-Object -First 1
if (-not $dump) {
    Write-Host "No snapshot found in backend\db\snapshot\. Run 'git pull' first." -ForegroundColor Red
    exit 1
}
Write-Host "Snapshot:" $dump.Name

# --- 2. Ask for the postgres password ---
Write-Host ""
Write-Host "Enter the password for the 'postgres' user (set when you installed PostgreSQL)."
$sec  = Read-Host "postgres password" -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec)
$pgpass = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
$env:PGPASSWORD = $pgpass

Write-Host ""
Write-Host "Testing connection..." -NoNewline
& $psql -U postgres -h localhost -p 5432 -d postgres -tAc "SELECT 1" *> $null
if ($LASTEXITCODE -ne 0) {
    Write-Host " FAILED" -ForegroundColor Red
    Write-Host "Could not connect. The password is probably wrong. Run the script again." -ForegroundColor Red
    exit 1
}
Write-Host " OK" -ForegroundColor Green

# --- 3. Fresh database ---
Write-Host "Recreating database 'agrika_gis'..." -NoNewline
& $psql -U postgres -h localhost -d postgres -c "DROP DATABASE IF EXISTS agrika_gis WITH (FORCE)" *> $null
& $psql -U postgres -h localhost -d postgres -c "CREATE DATABASE agrika_gis" *> $null
if ($LASTEXITCODE -ne 0) {
    Write-Host " FAILED" -ForegroundColor Red
    Write-Host "Close anything connected to agrika_gis (the backend, pgAdmin) and try again." -ForegroundColor Red
    exit 1
}
Write-Host " OK" -ForegroundColor Green

# --- 4. Restore ---
Write-Host "Restoring snapshot (takes a minute)..." -NoNewline
& $pgRestore -U postgres -h localhost -d agrika_gis --no-owner --no-privileges $dump.FullName *> "$scriptDir\_restore.log"
if ($LASTEXITCODE -ne 0) {
    Write-Host " FAILED" -ForegroundColor Red
    Write-Host "See backend\db\_restore.log. If it mentions postgis, install PostGIS via Stack Builder." -ForegroundColor Red
    exit 1
}
Write-Host " OK" -ForegroundColor Green

# --- 5. backend/.env ---
# The backend will not start without JWT_SECRET_KEY (the key that signs login tokens).
# It is NOT in the snapshot or the repo: every machine makes its own random one.
$envPath = Join-Path $backendDir ".env"
$jwt = -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 48 | ForEach-Object { [char]$_ })
if (-not (Test-Path $envPath)) {
    Write-Host "Writing backend\.env..." -NoNewline
    $encPass = [uri]::EscapeDataString($pgpass)
    $envContent = @"
# Local dev config - gitignored. Generated by restore_snapshot.ps1.
DATABASE_URL=postgresql+psycopg://postgres:$encPass@localhost:5432/agrika_gis
JWT_SECRET_KEY=$jwt
CORS_ORIGINS=http://localhost:5173
"@
    Set-Content -Path $envPath -Value $envContent -Encoding utf8
    Write-Host " OK" -ForegroundColor Green
} else {
    $lines = @(Get-Content $envPath)
    $current = $lines | Where-Object { $_ -match '^\s*JWT_SECRET_KEY\s*=' } | Select-Object -Last 1
    $value = if ($current) { ($current -split '=', 2)[1].Trim().Trim('"').Trim("'") } else { "" }
    if (-not $value -or $value -in @("dev-only-change-me", "change-this-to-a-long-random-string")) {
        Write-Host "Adding a JWT_SECRET_KEY to your backend\.env..." -NoNewline
        $lines = @($lines | Where-Object { $_ -notmatch '^\s*JWT_SECRET_KEY\s*=' }) + "JWT_SECRET_KEY=$jwt"
        # no BOM: python-dotenv would read it as part of the first key's name
        [IO.File]::WriteAllLines($envPath, [string[]]$lines, (New-Object System.Text.UTF8Encoding $false))
        Write-Host " OK" -ForegroundColor Green
    } else {
        Write-Host "Keeping your existing backend\.env (it already has a JWT_SECRET_KEY)."
    }
}

$env:PGPASSWORD = ""
Write-Host ""
Write-Host "=== Database restored! ===" -ForegroundColor Green
Write-Host "Next: create your login:" -ForegroundColor Green
Write-Host "  cd backend" -ForegroundColor Green
Write-Host "  .\venv\Scripts\python.exe scripts\create_user.py" -ForegroundColor Green
Write-Host ""
